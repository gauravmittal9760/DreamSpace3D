import { ITEM_BY_KEY } from "./catalog.js";
import * as A from "./modelsA.jsx";
import * as M from "./modelsB.jsx";

export function ItemModel({ item }) {
  const base = ITEM_BY_KEY[item.key];
  const p = base?.p || {};
  const props = { id: item.id, dims: item.dims, p, color: item.color || p.c || "#b68b63", type: item.type };
  switch (item.type) {
    case "wardrobe": return <A.Wardrobe {...props} />;
    case "bed": return <A.Bed {...props} />;
    case "bedside": return <A.Bedside {...props} />;
    case "sofa": return <A.Sofa {...props} />;
    case "coffee_table": return <A.CoffeeTable {...props} />;
    case "table": return <A.Table {...props} />;
    case "desk": return <A.Desk {...props} />;
    case "chair": return <A.Chair {...props} />;
    case "bookshelf": return <A.Bookshelf {...props} />;
    case "tv_unit": return <A.TvUnit {...props} />;
    case "tv": return <A.Tv {...props} />;
    case "dresser": return <A.CabinetLike {...props} kind="dresser" />;
    case "cabinet": return <A.CabinetLike {...props} kind="cabinet" />;
    case "shoe_rack": return <A.CabinetLike {...props} kind="cabinet" p={{ ...p, doors: p.doors || 0, drawers: p.bench ? 1 : 0 }} />;
    case "fan": return <M.Fan {...props} />;
    case "light": return <M.Light {...props} />;
    case "chandelier": return <M.Chandelier {...props} />;
    case "lamp": return <M.Lamp {...props} />;
    case "ac": return <M.Ac {...props} />;
    case "fridge": return <M.Fridge {...props} />;
    case "washing_machine": return <M.Washer {...props} />;
    case "microwave": return <M.Microwave {...props} />;
    case "geyser": return <M.Geyser {...props} />;
    case "kitchen_counter": return <M.KitchenCounter {...props} />;
    case "kitchen_island": return <M.KitchenIsland {...props} />;
    case "kitchen_sink": return <M.KitchenSink {...props} />;
    case "hob": return <M.Hob {...props} />;
    case "chimney": return <M.Chimney {...props} />;
    case "wall_cabinet": return <M.WallCabinet {...props} />;
    case "bathtub": return <M.Bathtub {...props} />;
    case "toilet": return <M.Toilet {...props} />;
    case "washbasin": return <M.Washbasin {...props} />;
    case "shower": return <M.Shower {...props} />;
    case "mirror": return <M.Mirror {...props} />;
    case "vanity": return <M.Vanity {...props} />;
    case "plant": return <M.Plant {...props} />;
    case "rug": return <M.Rug {...props} />;
    case "curtain": return <M.Curtain {...props} />;
    case "painting": return <M.Painting {...props} />;
    case "clock": return <M.Clock {...props} />;
    case "vase": return <M.Vase {...props} />;
    case "door": return <M.Door {...props} />;
    case "window": return <M.Window {...props} />;
    case "stairs": return <M.Stairs {...props} />;
    case "railing": return <M.Railing {...props} />;
    case "pillar": return <M.Pillar {...props} />;
    case "tree": return <M.Tree {...props} />;
    case "bush": return <M.Bush {...props} />;
    case "bench": return <M.Bench {...props} />;
    case "swing": return <M.Swing {...props} />;
    case "fountain": return <M.Fountain {...props} />;
    case "pool": return <M.Pool {...props} />;
    case "fence": return <M.Fence {...props} />;
    case "gate": return <M.Gate {...props} />;
    case "pergola": return <M.Pergola {...props} />;
    case "lamp_post": return <M.LampPost {...props} />;
    case "sunbed": return <M.Sunbed {...props} />;
    default: return <M.Basic {...props} />;
  }
}
